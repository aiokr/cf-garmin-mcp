import { DatabaseSync } from "node:sqlite";
import { writeFileSync, readFileSync, readdirSync } from "node:fs";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../apps/worker/src/auth/config.ts";

const database = new DatabaseSync(":memory:");
const directory = new URL("../apps/worker/migrations/", import.meta.url);
for (const name of readdirSync(directory)
  .filter((name) => name.endsWith(".sql"))
  .sort())
  database.exec(readFileSync(new URL(name, directory), "utf8"));
const options = authOptions({
  APP_URL: "http://localhost:8787",
  BETTER_AUTH_SECRET: "schema-generation-only-not-a-runtime-secret",
});
const migration = await getMigrations({ ...options, database });
const sql = await migration.compileMigrations();
if (process.argv.includes("--check")) {
  if (sql.replace(/[;\s]/g, ""))
    throw new Error(
      "Auth schema drift detected; generate a new migration before upgrading.",
    );
  console.log(
    "Better Auth schema matches locked packages and runtime options.",
  );
} else {
  const name = process.argv[2];
  if (!/^\d{4}_[a-z_]+\.sql$/.test(name || ""))
    throw new Error("Provide a new migration filename, e.g. 0004_oauth.sql");
  if (!sql.replace(/[;\s]/g, ""))
    throw new Error("No pending auth schema changes.");
  writeFileSync(
    new URL(name, directory),
    `-- Generated by Better Auth 1.7.28 getMigrations(). Do not edit by hand.\n${sql}\n`,
    { flag: "wx" },
  );
  console.log(`Generated ${name}; existing migrations were not overwritten.`);
}
database.close();
